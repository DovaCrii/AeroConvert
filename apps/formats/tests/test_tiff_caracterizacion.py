def _calcular(tmp_path: Path, caso: str) -> dict:
    ruta = tmp_path / "x.tif"
    ruta.write_bytes(CASOS[caso])
    try:
        cabecera = tiff.leer_cabecera(ruta)
    except tiff.NoEsTiff as fallo:
        return {"levanta": "NoEsTiff", "mensaje": str(fallo)}
    foto = dataclasses.asdict(cabecera)
    foto["_propiedades"] = {
        "nombre_compresion": cabecera.nombre_compresion,
        "nombre_fotometria": cabecera.nombre_fotometria,
        "tiene_alfa": cabecera.tiene_alfa,
        "megapixeles": cabecera.megapixeles,
        "tiene_piramides_internas": cabecera.tiene_piramides_internas,
        "bytes_sin_comprimir": cabecera.bytes_sin_comprimir,
        "gsd_cm": cabecera.gsd_cm,
        "extension_terreno_m": cabecera.extension_terreno_m,
        "necesitaba_bigtiff": cabecera.necesitaba_bigtiff,
    }
    return foto


