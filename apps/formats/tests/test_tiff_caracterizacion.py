"""Caracterización de `tiff.leer_cabecera` (F11.8, etapa 3), antes de partir `_leer_cabecera_de`.

`_leer_cabecera_de` mide ~170 líneas y mezcla tres cosas: reconocer la marca y los anchos
(clásico o BigTIFF), recorrer la cadena de directorios con sus topes, y armar la cabecera. Aquí
se arman TIFF a mano, byte a byte, para ejercitar **cada rama** —cadenas con pirámides,
máscaras y «menores sin declarar», ciclos, topes, directorios truncados, valores apuntados,
tipos raros— y se fija lo que devuelve hoy cada uno.

Complementa a `test_tiff.py`, que prueba la corrección del lector con el oráculo de su
constructor; esto solo congela el comportamiento para que el refactor no lo cambie.
"""

