SHORT, LONG, ASCII, DOUBLE, RATIONAL, LONG8 = 3, 4, 2, 12, 5, 16
_STRUCT = {1: "B", 3: "H", 4: "I", 12: "d", 16: "Q"}


def _tiff(ifds, *, orden="<", big=False, siguientes=None, marca=None, cola=b"") -> bytes:
    """Un TIFF armado a mano. `ifds` es una lista de `{etiqueta: (tipo, valores[, cuenta])}`.

    Los valores que no caben en el hueco van a un área detrás de los directorios, y cada IFD
    apunta al siguiente (o a lo que diga `siguientes[i]`, para fabricar ciclos).
    """
    hueco = 8 if big else 4
    ancho_off = "Q" if big else "I"
    tam_ifd = (lambda n: 8 + n * 20 + 8) if big else (lambda n: 2 + n * 12 + 4)
    inicio = 16 if big else 8

    posiciones, pos = [], inicio
    for ifd in ifds:
        posiciones.append(pos)
        pos += tam_ifd(len(ifd))
    base_area, area = pos, bytearray()

    cuerpos = []
    for i, ifd in enumerate(ifds):
        entradas = b""
        for etiqueta in sorted(ifd):
            entrada = ifd[etiqueta]
            tipo, valores = entrada[0], entrada[1]
            if isinstance(valores, bytes):
                datos, cuenta = valores, len(valores)
            else:
                datos = b"".join(struct.pack(orden + _STRUCT[tipo], v) for v in valores)
                cuenta = len(valores)
            if len(entrada) == 3:
                cuenta = entrada[2]
            if len(datos) <= hueco:
                valor = datos.ljust(hueco, b"\x00")
            else:
                valor = struct.pack(orden + ancho_off, base_area + len(area))
                area += datos
            entradas += (
                struct.pack(orden + "HH", etiqueta, tipo)
                + struct.pack(orden + ancho_off, cuenta)
                + valor
            )
        if siguientes and i in siguientes:
            sig = siguientes[i]
        else:
            sig = posiciones[i + 1] if i + 1 < len(ifds) else 0
        n = struct.pack(orden + ("Q" if big else "H"), len(ifd))
        cuerpos.append(n + entradas + struct.pack(orden + ancho_off, sig))

    marca_orden = b"II" if orden == "<" else b"MM"
    if big:
        cabecera = marca_orden + struct.pack(orden + "HHH", 43, 8, 0)
        cabecera += struct.pack(orden + "Q", posiciones[0] if ifds else 0)
    else:
        cabecera = marca_orden + struct.pack(orden + "H", 42)
        cabecera += struct.pack(orden + "I", posiciones[0] if ifds else 0)
    if marca is not None:
        cabecera = marca + cabecera[len(marca) :]
    return cabecera + b"".join(cuerpos) + bytes(area) + cola


def _principal(extra=None):
    """El IFD principal mínimo: 100×80, una banda de 8 bits."""
    ifd = {
        256: (SHORT, [100]),
        257: (SHORT, [80]),
        258: (SHORT, [8]),
        259: (SHORT, [1]),
        262: (SHORT, [1]),
        277: (SHORT, [1]),
    }
    ifd.update(extra or {})
    return ifd


def _reducido(ancho, bandera=None):
    ifd = {256: (SHORT, [ancho]), 257: (SHORT, [ancho * 4 // 5])}
    if bandera is not None:
        ifd[254] = (LONG, [bandera])
    return ifd


